const ICON_BY_KIND: Record<ComputeDriverKind, FunctionComponent<IconProps>> = {
  docker: DockerIcon,
  gce: GoogleCloudIcon,
  boat: BoatIcon,
};

/** Null: a driver this client cannot name, shown as a plain cloud. */
export function ComputeDriverIcon({
  kind,
  ...props
}: IconProps & { readonly kind: ComputeDriverKind | null }) {
  if (kind === null) return <CloudIcon {...props} />;
  const Icon = ICON_BY_KIND[kind];
  return <Icon {...props} />;
}
