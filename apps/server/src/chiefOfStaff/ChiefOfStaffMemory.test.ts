import * as NodeServices from "@effect/platform-node/NodeServices";
import { expect, it } from "@effect/vitest";
import { MemberId } from "@t3tools/contracts";
import * as Effect from "effect/Effect";
import * as FileSystem from "effect/FileSystem";
import * as Layer from "effect/Layer";
import * as Path from "effect/Path";

import { ServerConfig } from "../config.ts";
import {
  ChiefOfStaffMemory,
  MEMORY_BLOCK_LIMITS,
  type MemoryUpdate,
  layer as chiefOfStaffMemoryLayer,
} from "./ChiefOfStaffMemory.ts";

const member = MemberId.make("member-a");

const layerMemory = () =>
  chiefOfStaffMemoryLayer.pipe(
    Layer.provideMerge(ServerConfig.layerTest(process.cwd(), { prefix: "t3-cos-memory-test-" })),
    Layer.provideMerge(NodeServices.layer),
  );

const blocksFile = (stateDir: string, path: Path.Path, memberId: string) =>
  path.join(stateDir, "chief-of-staff", "memory", `${memberId}.json`);
const historyFile = (stateDir: string, path: Path.Path, memberId: string) =>
  path.join(stateDir, "chief-of-staff", "memory", `${memberId}.history.jsonl`);
const memoryFile = (stateDir: string, path: Path.Path, memberId: string) =>
  path.join(stateDir, "chief-of-staff", "home", memberId, "MEMORY.md");

const update = (memory: ChiefOfStaffMemory["Service"], change: MemoryUpdate) =>
  memory.update(member, change, "chief-of-staff");

it.effect("reads an empty memory and writes the MEMORY.md mirror", () =>
  Effect.gen(function* () {
    const memory = yield* ChiefOfStaffMemory;
    const config = yield* ServerConfig;
    const fs = yield* FileSystem.FileSystem;
    const path = yield* Path.Path;

    const snapshot = yield* memory.read(member);
    expect(snapshot.memberId).toBe(member);
    expect(snapshot.blocks.map((block) => block.label)).toEqual([
      "profile",
      "preferences",
      "standing_orders",
      "goals",
      "commitments",
      "projects",
      "notes",
    ]);
    expect(snapshot.blocks.every((block) => block.text === "" && block.size === 0)).toBe(true);
    expect(snapshot.blocks.find((block) => block.label === "profile")?.limit).toBe(
      MEMORY_BLOCK_LIMITS.profile,
    );

    const markdown = yield* fs.readFileString(memoryFile(config.stateDir, path, "member-a"));
    expect(markdown).toContain("Generated by Chief of staff");
    expect(markdown).not.toContain("## profile");
  }).pipe(Effect.provide(layerMemory())),
);

it.effect("sets a block, records history and renders only non-empty blocks", () =>
  Effect.gen(function* () {
    const memory = yield* ChiefOfStaffMemory;
    const config = yield* ServerConfig;
    const fs = yield* FileSystem.FileSystem;
    const path = yield* Path.Path;

    const written = yield* update(memory, {
      label: "profile",
      op: "set",
      text: "Rutvik, founder. Prefers short answers.",
    });
    expect(written.size).toBe(Array.from(written.text).length);
    expect(written.text).toContain("Rutvik");

    const snapshot = yield* memory.read(member);
    expect(snapshot.blocks.find((block) => block.label === "profile")?.text).toContain("Rutvik");

    const markdown = yield* fs.readFileString(memoryFile(config.stateDir, path, "member-a"));
    expect(markdown).toContain("## profile");
    expect(markdown).not.toContain("## notes");

    const stored = yield* fs.readFileString(blocksFile(config.stateDir, path, "member-a"));
    expect(JSON.parse(stored).profile).toContain("Rutvik");

    const history = yield* memory.history(member);
    expect(history).toHaveLength(1);
    expect(history[0]).toMatchObject({
      label: "profile",
      op: "set",
      before: "",
      actor: "chief-of-staff",
    });
    expect(history[0]?.after).toContain("Rutvik");
  }).pipe(Effect.provide(layerMemory())),
);

it.effect("rejects a write over the block limit and says how to fix it", () =>
  Effect.gen(function* () {
    const memory = yield* ChiefOfStaffMemory;
    yield* update(memory, { label: "profile", op: "set", text: "seed" });

    const error = yield* update(memory, {
      label: "profile",
      op: "set",
      text: "x".repeat(MEMORY_BLOCK_LIMITS.profile + 1),
    }).pipe(Effect.flip);
    expect(error.reason).toBe("block_too_large");
    expect(error.message).toContain(String(MEMORY_BLOCK_LIMITS.profile));
    expect(error.message).toContain("it is 4 now");
    expect(error.message).toContain("Condense");

    const snapshot = yield* memory.read(member);
    expect(snapshot.blocks.find((block) => block.label === "profile")?.text).toBe("seed");
  }).pipe(Effect.provide(layerMemory())),
);

it.effect("replace needs oldText to match exactly once", () =>
  Effect.gen(function* () {
    const memory = yield* ChiefOfStaffMemory;
    yield* update(memory, { label: "notes", op: "set", text: "likes cats and cats" });

    const missing = yield* update(memory, {
      label: "notes",
      op: "replace",
      oldText: "dogs",
      text: "dogs",
    }).pipe(Effect.flip);
    expect(missing.reason).toBe("replace_failed");
    expect(missing.message).toContain("not found");

    const ambiguous = yield* update(memory, {
      label: "notes",
      op: "replace",
      oldText: "cats",
      text: "dogs",
    }).pipe(Effect.flip);
    expect(ambiguous.reason).toBe("replace_failed");
    expect(ambiguous.message).toContain("more than once");

    const replaced = yield* update(memory, {
      label: "notes",
      op: "replace",
      oldText: "likes cats and cats",
      text: "likes dogs",
    });
    expect(replaced.text).toBe("likes dogs");

    const noOldText = yield* update(memory, {
      label: "notes",
      op: "replace",
      text: "ignored",
    }).pipe(Effect.flip);
    expect(noOldText.reason).toBe("replace_failed");
  }).pipe(Effect.provide(layerMemory())),
);

it.effect("append adds a line and never loses concurrent writes", () =>
  Effect.gen(function* () {
    const memory = yield* ChiefOfStaffMemory;
    yield* Effect.all(
      Array.from({ length: 10 }, (_, index) =>
        update(memory, { label: "notes", op: "append", text: `note-${index}` }),
      ),
      { concurrency: "unbounded" },
    );
    const snapshot = yield* memory.read(member);
    const text = snapshot.blocks.find((block) => block.label === "notes")?.text ?? "";
    for (let index = 0; index < 10; index += 1) expect(text).toContain(`note-${index}`);
    expect(text.split("\n")).toHaveLength(10);
  }).pipe(Effect.provide(layerMemory())),
);

it.effect("history filters by label and returns the most recent first", () =>
  Effect.gen(function* () {
    const memory = yield* ChiefOfStaffMemory;
    const config = yield* ServerConfig;
    const fs = yield* FileSystem.FileSystem;
    const path = yield* Path.Path;

    for (const label of ["profile", "goals", "profile"] as const) {
      yield* update(memory, { label, op: "append", text: label });
    }

    const all = yield* memory.history(member, { limit: 2 });
    expect(all).toHaveLength(2);
    expect(all[0]?.label).toBe("profile");

    const goals = yield* memory.history(member, { label: "goals" });
    expect(goals).toHaveLength(1);
    expect(goals[0]?.label).toBe("goals");

    const lines = yield* fs.readFileString(historyFile(config.stateDir, path, "member-a"));
    expect(lines.trim().split("\n")).toHaveLength(3);
  }).pipe(Effect.provide(layerMemory())),
);

it.effect("refuses a member id that could escape the memory folder", () =>
  Effect.gen(function* () {
    const memory = yield* ChiefOfStaffMemory;
    for (const bad of ["../escape", "a/b", ".."]) {
      const error = yield* memory.read(MemberId.make(bad)).pipe(Effect.flip);
      expect(error.reason).toBe("invalid_member");
    }
  }).pipe(Effect.provide(layerMemory())),
);
