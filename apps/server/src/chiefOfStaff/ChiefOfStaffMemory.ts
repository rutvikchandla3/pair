import { MemberId } from "@t3tools/contracts";
import { writeFileStringAtomically } from "@t3tools/shared/atomicWrite";
import * as Context from "effect/Context";
import * as DateTime from "effect/DateTime";
import * as Effect from "effect/Effect";
import * as FileSystem from "effect/FileSystem";
import * as HashMap from "effect/HashMap";
import * as Layer from "effect/Layer";
import * as Option from "effect/Option";
import * as Path from "effect/Path";
import * as Schema from "effect/Schema";
import * as Semaphore from "effect/Semaphore";
import * as SynchronizedRef from "effect/SynchronizedRef";

import { ServerConfig } from "../config.ts";

/** The labels and per-block character caps the agent curates within. */
const MEMORY_BLOCK_LABEL_VALUES = [
  "profile",
  "preferences",
  "standing_orders",
  "goals",
  "commitments",
  "projects",
  "notes",
] as const;

export const MemoryBlockLabel = Schema.Literals(MEMORY_BLOCK_LABEL_VALUES);
export type MemoryBlockLabel = typeof MemoryBlockLabel.Type;

export const MEMORY_BLOCK_LIMITS: Record<MemoryBlockLabel, number> = {
  profile: 1500,
  preferences: 2000,
  standing_orders: 2000,
  goals: 1500,
  commitments: 2000,
  projects: 3000,
  notes: 3000,
};

const MemoryUpdateOp = Schema.Literals(["replace", "append", "set"]);

export const MemoryUpdate = Schema.Struct({
  label: MemoryBlockLabel,
  op: MemoryUpdateOp,
  oldText: Schema.optional(Schema.String),
  text: Schema.String,
});
export type MemoryUpdate = typeof MemoryUpdate.Type;

export const MemoryBlock = Schema.Struct({
  label: MemoryBlockLabel,
  text: Schema.String,
  size: Schema.Number,
  limit: Schema.Number,
});
export type MemoryBlock = typeof MemoryBlock.Type;

export const MemorySnapshot = Schema.Struct({
  memberId: MemberId,
  blocks: Schema.Array(MemoryBlock),
});
export type MemorySnapshot = typeof MemorySnapshot.Type;

export const MemoryHistoryEntry = Schema.Struct({
  at: Schema.Number,
  label: MemoryBlockLabel,
  op: MemoryUpdateOp,
  before: Schema.String,
  after: Schema.String,
  actor: Schema.String,
});
export type MemoryHistoryEntry = typeof MemoryHistoryEntry.Type;

export class ChiefOfStaffMemoryError extends Schema.TaggedError<ChiefOfStaffMemoryError>()(
  "ChiefOfStaffMemoryError",
  {
    reason: Schema.Literals([
      "invalid_member",
      "replace_failed",
      "unknown_block",
      "block_too_large",
      "io_failed",
    ]),
    message: Schema.String,
  },
) {}

export interface MemoryHistoryQuery {
  readonly label?: MemoryBlockLabel | undefined;
  readonly limit?: number | undefined;
}

/**
 * A member's durable memory: a few labelled, size-capped blocks the agent must
 * curate, a change history, and a generated `MEMORY.md` mirror in the home
 * thread's folder.
 */
export class ChiefOfStaffMemory extends Context.Service<
  ChiefOfStaffMemory,
  {
    readonly read: (memberId: MemberId) => Effect.Effect<MemorySnapshot, ChiefOfStaffMemoryError>;
    readonly update: (
      memberId: MemberId,
      change: MemoryUpdate,
      actor: string,
    ) => Effect.Effect<MemoryBlock, ChiefOfStaffMemoryError>;
    readonly history: (
      memberId: MemberId,
      query?: MemoryHistoryQuery | undefined,
    ) => Effect.Effect<ReadonlyArray<MemoryHistoryEntry>, ChiefOfStaffMemoryError>;
    /** Writes `MEMORY.md` from the current blocks and returns it. */
    readonly render: (memberId: MemberId) => Effect.Effect<string, ChiefOfStaffMemoryError>;
  }
>()("t3/chiefOfStaff/ChiefOfStaffMemory") {}

const LABELS = MEMORY_BLOCK_LABEL_VALUES;
const BLOCKS_JSON = Schema.fromJsonString(Schema.Record(Schema.String, Schema.String));
const decodeBlocks = Schema.decodeEffect(BLOCKS_JSON);
const encodeBlocks = Schema.encodeEffect(BLOCKS_JSON);
const HISTORY_ENTRY_JSON = Schema.fromJsonString(MemoryHistoryEntry);
const encodeHistoryEntry = Schema.encodeEffect(HISTORY_ENTRY_JSON);
const decodeHistoryEntry = Schema.decodeUnknownOption(MemoryHistoryEntry);

type Blocks = Record<MemoryBlockLabel, string>;

const emptyBlocks = (): Blocks => ({
  profile: "",
  preferences: "",
  standing_orders: "",
  goals: "",
  commitments: "",
  projects: "",
  notes: "",
});

const normalizeBlocks = (raw: Record<string, string>): Blocks => {
  const blocks = emptyBlocks();
  for (const label of LABELS) {
    blocks[label] = raw[label] ?? "";
  }
  return blocks;
};

/** Code points, so an emoji counts as the one character the user sees. */
const characterCount = (text: string) => Array.from(text).length;

const RENDER_HEADER =
  "<!-- Generated by Chief of staff from its memory blocks. Edit through the `cos_memory_*` tools; direct edits are overwritten. -->";

const renderMemoryMarkdown = (blocks: Blocks): string => {
  const sections = LABELS.filter((label) => blocks[label].trim().length > 0).map(
    (label) => `## ${label}\n\n${blocks[label].trim()}\n`,
  );
  return `${RENDER_HEADER}\n\n${sections.join("\n")}`;
};

const MEMBER_ID_PATTERN = /^[A-Za-z0-9][A-Za-z0-9_.:-]{0,127}$/;

const memberIdProblem = (memberId: string): string | undefined => {
  if (memberId.length === 0) return "A member id is required.";
  if (!MEMBER_ID_PATTERN.test(memberId) || memberId.includes("..")) {
    return `"${memberId}" is not a valid member id; it must be 1-128 letters, digits, ".", "_", ":" or "-", and cannot contain "..".`;
  }
  return undefined;
};

const nextBlockText = (
  change: MemoryUpdate,
  before: string,
): Effect.Effect<string, ChiefOfStaffMemoryError> => {
  if (change.op === "set") return Effect.succeed(change.text);
  if (change.op === "append") {
    return Effect.succeed(before.length === 0 ? change.text : `${before}\n${change.text}`);
  }
  const oldText = change.oldText;
  if (oldText === undefined || oldText.length === 0) {
    return Effect.fail(
      new ChiefOfStaffMemoryError({
        reason: "replace_failed",
        message:
          "A replace needs `old_text`: the exact existing text to swap out. Read the block and copy a substring of it.",
      }),
    );
  }
  const first = before.indexOf(oldText);
  const last = before.lastIndexOf(oldText);
  if (first === -1) {
    return Effect.fail(
      new ChiefOfStaffMemoryError({
        reason: "replace_failed",
        message: `\`old_text\` was not found in ${change.label}. Read the block and pass a substring that appears exactly once.`,
      }),
    );
  }
  if (first !== last) {
    return Effect.fail(
      new ChiefOfStaffMemoryError({
        reason: "replace_failed",
        message: `\`old_text\` appears more than once in ${change.label}. Include more surrounding text so it matches exactly once.`,
      }),
    );
  }
  return Effect.succeed(
    before.slice(0, first) + change.text + before.slice(first + oldText.length),
  );
};

const make = Effect.gen(function* () {
  const config = yield* ServerConfig;
  const fileSystem = yield* FileSystem.FileSystem;
  const path = yield* Path.Path;
  const directory = path.join(config.stateDir, "chief-of-staff", "memory");
  const locks = yield* SynchronizedRef.make(HashMap.empty<string, Semaphore.Semaphore>());

  const blocksFile = (memberId: string) => path.join(directory, `${memberId}.json`);
  const historyFile = (memberId: string) => path.join(directory, `${memberId}.history.jsonl`);
  const homeDirectory = (memberId: string) =>
    path.join(config.stateDir, "chief-of-staff", "home", memberId);
  const memoryFile = (memberId: string) => path.join(homeDirectory(memberId), "MEMORY.md");

  const ensureMemberId = (memberId: MemberId) => {
    const problem = memberIdProblem(String(memberId));
    return problem === undefined
      ? Effect.void
      : Effect.fail(new ChiefOfStaffMemoryError({ reason: "invalid_member", message: problem }));
  };

  const io =
    (action: string) =>
    <A, E, R>(effect: Effect.Effect<A, E, R>): Effect.Effect<A, ChiefOfStaffMemoryError, R> =>
      Effect.mapError(
        effect,
        () =>
          new ChiefOfStaffMemoryError({
            reason: "io_failed",
            message: `${action} failed. Check that the server can write its state directory.`,
          }),
      );

  const withMemberLock = <A, E, R>(memberId: string, effect: Effect.Effect<A, E, R>) =>
    Effect.flatMap(
      SynchronizedRef.modifyEffect(locks, (map) => {
        const existing = HashMap.get(map, memberId);
        return Option.isSome(existing)
          ? Effect.succeed([existing.value, map] as const)
          : Effect.map(
              Semaphore.make(1),
              (created) => [created, HashMap.set(map, memberId, created)] as const,
            );
      }),
      (semaphore) => semaphore.withPermits(1)(effect),
    );

  const writeAtomically = (filePath: string, contents: string) =>
    writeFileStringAtomically({ filePath, contents }).pipe(
      Effect.provideService(FileSystem.FileSystem, fileSystem),
      Effect.provideService(Path.Path, path),
    );

  const readBlocks = Effect.fn("ChiefOfStaffMemory.readBlocks")(function* (memberId: string) {
    const contents = yield* fileSystem
      .readFileString(blocksFile(memberId))
      .pipe(Effect.orElseSucceed(() => ""));
    if (contents.trim().length === 0) return emptyBlocks();
    const raw = yield* decodeBlocks(contents).pipe(
      io("Reading the memory blocks"),
      Effect.orElseSucceed((): Record<string, string> => ({})),
    );
    return normalizeBlocks(raw);
  });

  const writeBlocks = Effect.fn("ChiefOfStaffMemory.writeBlocks")(function* (
    memberId: string,
    blocks: Blocks,
  ) {
    yield* io("Creating the memory directory")(
      fileSystem.makeDirectory(directory, { recursive: true }),
    );
    const contents = yield* encodeBlocks(blocks).pipe(io("Encoding the memory blocks"));
    yield* io("Writing the memory blocks")(writeAtomically(blocksFile(memberId), contents));
  });

  const appendHistory = Effect.fn("ChiefOfStaffMemory.appendHistory")(function* (
    memberId: string,
    entry: MemoryHistoryEntry,
  ) {
    yield* io("Creating the memory directory")(
      fileSystem.makeDirectory(directory, { recursive: true }),
    );
    const line = yield* encodeHistoryEntry(entry).pipe(io("Encoding the memory history"));
    yield* io("Appending to the memory history")(
      fileSystem.writeFileString(historyFile(memberId), `${line}\n`, { flag: "a" }),
    );
  });

  const writeMemoryFile = Effect.fn("ChiefOfStaffMemory.writeMemoryFile")(function* (
    memberId: string,
    blocks: Blocks,
  ) {
    const markdown = renderMemoryMarkdown(blocks);
    yield* io("Creating the home folder")(
      fileSystem.makeDirectory(homeDirectory(memberId), { recursive: true }),
    );
    yield* io("Writing MEMORY.md")(writeAtomically(memoryFile(memberId), markdown));
    return markdown;
  });

  const blockView = (label: MemoryBlockLabel, text: string): MemoryBlock => ({
    label,
    text,
    size: characterCount(text),
    limit: MEMORY_BLOCK_LIMITS[label],
  });

  const snapshot = (memberId: MemberId, blocks: Blocks): MemorySnapshot => ({
    memberId,
    blocks: LABELS.map((label) => blockView(label, blocks[label])),
  });

  const read = Effect.fn("ChiefOfStaffMemory.read")(function* (memberId: MemberId) {
    yield* ensureMemberId(memberId);
    return yield* withMemberLock(
      String(memberId),
      Effect.gen(function* () {
        const blocks = yield* readBlocks(String(memberId));
        // Keep the on-disk mirror current even before the first write.
        yield* writeMemoryFile(String(memberId), blocks);
        return snapshot(memberId, blocks);
      }),
    );
  });

  const update = Effect.fn("ChiefOfStaffMemory.update")(function* (
    memberId: MemberId,
    change: MemoryUpdate,
    actor: string,
  ) {
    yield* ensureMemberId(memberId);
    return yield* withMemberLock(
      String(memberId),
      Effect.gen(function* () {
        const blocks = yield* readBlocks(String(memberId));
        const before = blocks[change.label];
        const after = yield* nextBlockText(change, before);
        const limit = MEMORY_BLOCK_LIMITS[change.label];
        if (characterCount(after) > limit) {
          return yield* new ChiefOfStaffMemoryError({
            reason: "block_too_large",
            message: `"${change.label}" would be ${characterCount(after)} characters, over its ${limit} limit (it is ${characterCount(before)} now). Condense the block with a smaller \`replace\` first.`,
          });
        }
        const next = { ...blocks, [change.label]: after };
        yield* writeBlocks(String(memberId), next);
        yield* appendHistory(String(memberId), {
          at: DateTime.toEpochMillis(yield* DateTime.now),
          label: change.label,
          op: change.op,
          before,
          after,
          actor,
        });
        yield* writeMemoryFile(String(memberId), next);
        return blockView(change.label, after);
      }),
    );
  });

  const history = Effect.fn("ChiefOfStaffMemory.history")(function* (
    memberId: MemberId,
    query?: MemoryHistoryQuery,
  ) {
    yield* ensureMemberId(memberId);
    const limit = Math.max(1, Math.min(query?.limit ?? 20, 50));
    const contents = yield* fileSystem
      .readFileString(historyFile(String(memberId)))
      .pipe(Effect.orElseSucceed(() => ""));
    const entries = contents
      .split("\n")
      .flatMap((line): ReadonlyArray<MemoryHistoryEntry> => {
        if (line.trim().length === 0) return [];
        let parsed: unknown;
        try {
          parsed = JSON.parse(line);
        } catch {
          return [];
        }
        return Option.toArray(decodeHistoryEntry(parsed));
      })
      .filter((entry) => query?.label === undefined || entry.label === query.label);
    // Most recent first, so a bounded read shows the latest changes.
    return entries.slice(-limit).reverse();
  });

  const render = Effect.fn("ChiefOfStaffMemory.render")(function* (memberId: MemberId) {
    yield* ensureMemberId(memberId);
    return yield* withMemberLock(
      String(memberId),
      Effect.gen(function* () {
        const blocks = yield* readBlocks(String(memberId));
        return yield* writeMemoryFile(String(memberId), blocks);
      }),
    );
  });

  return ChiefOfStaffMemory.of({ read, update, history, render });
});

export const layer = Layer.effect(ChiefOfStaffMemory, make);
